def refine_all_slides():
    print("=" * 80)
    print("✨ [송림야담] 120개 슬라이드 문장부호(쉼표/마침표/말줄임표) 전수 보완 및 연음 동기화")
    print("=" * 80)
    
    with open(SLIDES_DATA_PATH, "r", encoding="utf-8") as f:
        slides = json.load(f)
        
    updated_count = 0
    for s in slides:
        idx = int(s["slide_index"])
        if idx in PUNCTUATION_REFINED_SCRIPTS:
            refined_voice = PUNCTUATION_REFINED_SCRIPTS[idx].strip()
            
            # 발음 정규화 적용 (국립국어원 표준 연음 + 조사 '의'->[에] 등)
            refined_phonetic = normalize_phonetics_for_tts(refined_voice)
            
            # 저장
            s["voice_script"] = refined_voice
            s["phonetic_script"] = refined_phonetic
            updated_count += 1
            
    with open(SLIDES_DATA_PATH, "w", encoding="utf-8") as f:
        json.dump(slides, f, ensure_ascii=False, indent=2)
        
    print(f"🎉 120개 중 {updated_count}개 슬라이드의 voice_script 및 phonetic_script가 완벽히 갱신되었습니다!")

if __name__ == "__main__":
    refine_all_slides()
