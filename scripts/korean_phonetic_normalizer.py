"""
korean_phonetic_normalizer.py
─────────────────────────────
국립국어원 표준 발음법 및 AI TTS 음절 보호 / 연음 / 구개음화 / 장음 정규화 모듈
- 쌍받침(ㄲ) 및 겹받침 연음 (문밖을 -> 문바끌, 밖을 -> 바끌, 넋을 -> 넉슬 등)
- 관형격 조사 '의' -> [에] 자연스러운 발음 유도 (문밖의 -> 문밖에, 마님의 -> 마님에 등)
- 합성어 'ㄴ' 첨가 규칙 (산약초 -> 산냑초, 맨입 -> 맨닙 등)
- 구개음화 및 ㅌ 받침 연음 (살갗이 -> 살까치, 샅샅이 -> 삳싸치 등)
- 받침 'ㅊ' 연음 (눈빛엔 -> 눈비첸, 눈빛이 -> 눈비치 등)
- 비음화 / 유음화 / 경음화 TTS 오독 방지 보정
- 말줄임표 앞 끝음절 모음 삼킴(탈락) 방지 및 호흡 쉼표 보호
"""

import re

PRONUNCIATION_MAP = [
    # 1. 특정 대사 호흡 및 끝음절 탈락 방지 (슬라이드 59, 60 등)
    (r'좋으니\s*부디\s*살아서\s*살아서만', '좋으니, 부디... 살아서, 살아서만'),
    (r'나서는\s*진우\.\.\.', '나서는 진우, ...'),
    (r'나서는\s*진우\b', '나서는 진우'),

    # 2. 쌍받침(ㄲ) 연음 규칙 (제13항: ㄲ + 모음 조사 -> [끌, 끈, 끼, 끄, 께])
    (r'\b문밖을\b', '문바끌'),
    (r'\b문밖은\b', '문바끈'),
    (r'\b문밖이\b', '문바끼'),
    (r'\b문밖으로\b', '문바끄로'),
    (r'\b문밖에서\b', '문바께서'),
    (r'\b문밖에\b', '문바께'),
    (r'\b창밖을\b', '창바끌'),
    (r'\b창밖은\b', '창바끈'),
    (r'\b창밖이\b', '창바끼'),
    (r'\b창밖으로\b', '창바끄로'),
    (r'\b창밖에서\b', '창바께서'),
    (r'\b창밖에\b', '창바께'),
    (r'\b밖을\b', '바끌'),
    (r'\b밖은\b', '바끈'),
    (r'\b밖이\b', '바끼'),
    (r'\b밖으로\b', '바끄로'),
    (r'\b밖에서\b', '바께서'),
    (r'\b밖에\b', '바께'),

    # 3. 조사 '의' -> '에' ([에]로 발음되어야 자연스러운 관형격 조사)
    (r'\b문밖의\b', '문바께'),
    (r'\b창밖의\b', '창바께'),
    (r'\b마님의\b', '마님에'),
    (r'\b가문의\b', '가문에'),
    (r'\b세도의\b', '세도에'),
    (r'\b역모의\b', '역모에'),
    (r'\b희망의\b', '희망에'),
    (r'\b은혜의\b', '은혜에'),
    (r'\b세상의\b', '세상에'),
    (r'\b사람의\b', '사람에'),
    (r'\b마음의\b', '마음에'),
    (r'\b자신의\b', '자신에'),
    (r'\b그의\b', '그에'),
    (r'\b그녀의\b', '그녀에'),
    (r'\b누구의\b', '누구에'),
    (r'\b모두의\b', '모두에'),
    (r'\b밤의\b', '밤에'),
    (r'\b눈물의\b', '눈물에'),
    (r'\b슬픔의\b', '슬픔에'),
    (r'\b비극의\b', '비극에'),
    (r'\b운명의\b', '운명에'),
    (r'\b진실의\b', '진실에'),

    # 일반 명사 뒤의 관형격 조사 '의' -> [에]
    (r'([가-힣]{2,})의\b', r'\1에'),

    # 4. 받침 'ㅊ' 연음 및 음가 교정 (제13항)
    (r'\b달빛\s*아래\b', '달삣 아래'),
    (r'\b달빛이\b', '달비치'),
    (r'\b달빛은\b', '달비츤'),
    (r'\b달빛을\b', '달비츨'),
    (r'\b달빛에\b', '달비체'),
    (r'\b달빛마저\b', '달빈마저'),
    (r'\b달빛조차\b', '달비쪼차'),
    (r'\b달빛\b', '달삣'),
    (r'\b눈빛엔\b', '눈비첸'),
    (r'\b눈빛이\b', '눈비치'),
    (r'\b눈빛을\b', '눈비츨'),
    (r'\b눈빛에\b', '눈비체'),
    (r'\b빛엔\b', '비첸'),
    (r'\b빛이\b', '비치'),
    (r'\b빛을\b', '비츨'),
    (r'\b빛에\b', '비체'),

    # 5. 합성어 'ㄴ' 첨가 규칙 (제29항)
    (r'\b산약초\b', '산냑초'),
    (r'\b산약초를\b', '산냑초를'),
    (r'\b산약초의\b', '산냑초에'),

    # 6. 구개음화 및 ㅌ 받침 연음 (제17항)
    (r'\b살갗이\b', '살까치'),
    (r'\b살갗을\b', '살까츨'),
    (r'\b살갗에\b', '살까체'),
    (r'\b샅샅이\b', '삳싸치'),

    # 7. 비음화 및 유음화 교정 (제18항~제20항)
    (r'\b백 년\b', '뱅 년'),
    (r'\b십 년\b', '심 년'),
    (r'\b10년\b', '심 년'),
    (r'\b100년\b', '뱅 년'),
    (r'\b군량미\b', '군냥미'),
    (r'\b신문로\b', '신문노'),

    # 8. 겹받침 연음 및 경음화 교정
    (r'\b월이댁에게\b', '월이땍에게'),
    (r'\b월이댁의\b', '월이땍에'),
    (r'\b월이댁은\b', '월이땍은'),
    (r'\b월이댁이\b', '월이땍이'),
    (r'\b월이댁을\b', '월이땍을'),
    (r'\b월이댁\b', '월이땍'),
    (r'\b거센\b', '거쎈'),
    (r'\b거세게\b', '거쎄게'),
    (r'\b넋을\b', '넉슬'),
    (r'\b넋이\b', '넉시'),
    (r'\b흙을\b', '흘글'),
    (r'\b닭을\b', '달글'),
    (r'\b달빛조차\b', '달비쪼차'),
    (r'\b빛조차\b', '비쪼차'),
    (r'\b밤낮을\b', '밤나즐'),
    (r'\b손가락질\b', '손까락찔'),
]

def normalize_phonetics_for_tts(text: str) -> str:
    """TTS 엔진이 자연스러운 한국어 표준 연음 및 온전한 음절로 발음하도록 텍스트 교정"""
    for pattern, replacement in PRONUNCIATION_MAP:
        text = re.sub(pattern, replacement, text)
    
    # 말줄임표 직전 명사 끝음절 탈락 방지: 자음/모음 뒤 바로 '...'가 오면 ', ...'로 안전 완충
    text = re.sub(r'([가-힣])\.\.\.', r'\1, ...', text)
    return text

if __name__ == "__main__":
    test_cases = [
        "돌쇠는 문밖을 에워싼 횃불들을 예리하게 쏘아보며",
        "마님의 눈빛엔 범상치 않은 기품이 서려 있었습니다",
        "산약초를 캐내어 마님께 바쳤습니다",
        "자신은 살갗이 질긴 머슴이니",
        "샅샅이 뒤져 단 한 놈도 살려두지 말라",
        "달빛 아래 고요한 밤 달빛이 비치자"
    ]
    for tc in test_cases:
        print(f"원문: {tc} -> 변환: {normalize_phonetics_for_tts(tc)}")
