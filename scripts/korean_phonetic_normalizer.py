import json
from pathlib import Path

LEXICON_PATH = Path(__file__).resolve().parent.parent / "data" / "korean_pronunciation_lexicon.json"
LOADED_LEXICON = {}
if LEXICON_PATH.exists():
    try:
        with open(LEXICON_PATH, "r", encoding="utf-8") as _f:
            LOADED_LEXICON = json.load(_f)
    except Exception as _e:
        print(f"Warning: Failed to load lexicon: {_e}")

# 길이 역순으로 정렬하여 복합어/긴 구문이 단일 어휘보다 먼저 치환되도록 보장
SORTED_LEXICON_ITEMS = sorted(LOADED_LEXICON.items(), key=lambda x: len(x[0]), reverse=True)

def normalize_phonetics_for_tts(text: str) -> str:
    """TTS 엔진이 자연스러운 한국어 표준 연음 및 온전한 음절로 발음하도록 텍스트 교정"""
    # 1. 표준 발음 DB 룩업 테이블 적용
    for orig, phon in SORTED_LEXICON_ITEMS:
        # 단어 경계 또는 어미/조사 결합 시 치환
        if orig in text:
            # 안전한 정규식 단어 치환
            text = re.sub(re.escape(orig), phon, text)

    # 2. 음운론적 규칙 맵 적용 (연음, 관형격 '의' -> [에], 비음화, 겹받침 등)
    for pattern, replacement in PRONUNCIATION_MAP:
        text = re.sub(pattern, replacement, text)
    
    # 말줄임표 직전 명사 끝음절 탈락 방지: 자음/모음 뒤 바로 '...'가 오면 ', ...'로 안전 완충
    text = re.sub(r'([가-힣])\.\.\.', r'\1, ...', text)

    # 사용자 명시 교정 확정 보장: 샅샅이 뒤져 -> 샅샅이 뒤져,
    text = re.sub(r'(삳싸치|샅샅이)[,\s]*(뒤져|두져)[,\s]*', '샅샅이 뒤져, ', text)
    return text

